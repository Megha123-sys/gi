// Typing effect for hero title
function typeWriterEffect() {
    const titleElement = document.querySelector('.hero-title');
    if (!titleElement) return;
    
    const originalText = titleElement.innerHTML;
    const textWithoutSpan = titleElement.textContent;
    
    // Only run on larger screens
    if (window.innerWidth > 768) {
        titleElement.innerHTML = '';
        let i = 0;
        
        function typeWriter() {
            if (i < textWithoutSpan.length) {
                if (textWithoutSpan.substr(i, 5) === 'Megha') {
                    titleElement.innerHTML += '<span class="highlight">Megha</span>';
                    i += 5;
                } else {
                    titleElement.innerHTML += textWithoutSpan.charAt(i);
                    i++;
                }
                setTimeout(typeWriter, 100);
            }
        }
        
        setTimeout(typeWriter, 500);
    }
}

