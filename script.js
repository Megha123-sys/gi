// Counter animation for stats
function animateCounters() {
    const counters = document.querySelectorAll('.stat h3, .metric-value');
    
    counters.forEach(counter => {
        const target = counter.textContent;
        const isPercentage = target.includes('%');
        const isCurrency = target.includes('₹');
        const isMultiplier = target.includes('x');
        const hasPlus = target.includes('+');
        
        // Extract numeric value
        let numericValue = target.replace(/[^\d.]/g, '');
        if (numericValue.includes('.')) {
            numericValue = parseFloat(numericValue);
        } else {
            numericValue = parseInt(numericValue);
        }
        
        if (numericValue && numericValue > 0) {
            let currentValue = 0;
            const increment = numericValue / 50; // 50 steps
            const timer = setInterval(() => {
                currentValue += increment;
                
                if (currentValue >= numericValue) {
                    currentValue = numericValue;
                    clearInterval(timer);
                }
                
                let displayValue = Math.floor(currentValue);
                
                // Format based on original format
                if (isCurrency) {
                    if (numericValue >= 10000000) { // Crores
                        displayValue = (currentValue / 10000000).toFixed(1) + 'Cr';
                    } else if (numericValue >= 100000) { // Lakhs
                        displayValue = (currentValue / 100000).toFixed(0) + 'L';
                    } else if (numericValue >= 1000) { // Thousands
                        displayValue = (currentValue / 1000).toFixed(0) + 'K';
                    }
                    displayValue = '₹' + displayValue;
                } else if (numericValue >= 1000000) {
                    displayValue = (currentValue / 1000000).toFixed(0) + 'M';
                } else if (numericValue >= 1000) {
                    displayValue = (currentValue / 1000).toFixed(0) + 'K';
                }
                
                if (isPercentage) displayValue += '%';
                if (isMultiplier) displayValue += 'x';
                if (hasPlus) displayValue += '+';
                
                counter.textContent = displayValue;
            }, 50);
        }
    });
}

// Trigger counter animation when stats section is visible
const statsSection = document.querySelector('.hero-stats');
if (statsSection) {
    const statsObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                animateCounters();
                statsObserver.unobserve(entry.target);
            }
        });
    }, { threshold: 0.5 });
    
    statsObserver.observe(statsSection);
}

// Parallax effect for hero background
function handleParallax() {
    const hero = document.querySelector('.hero');
    const scrolled = window.pageYOffset;
    const rate = scrolled * -0.5;
    
    if (hero && scrolled < hero.offsetHeight) {
        hero.style.transform = `translateY(${rate}px)`;
    }
}

window.addEventListener('scroll', handleParallax);

